/** German deadlines are German deadlines — never render them in the host's zone. */
function formatDate(date: Date, locale: Locale): string {
  return new Intl.DateTimeFormat(locale === "de" ? "de-DE" : "en-GB", {
    dateStyle: "long",
    timeZone: "Europe/Berlin",
  }).format(date);
}

function daysUntil(date: Date): number {
  return Math.ceil((date.getTime() - Date.now()) / 86_400_000);
}

/** The executive summary opener, trimmed to something an inbox will show. */
function trimHeadline(text: string, limit = 340): string {
  const collapsed = text.replace(/\s+/g, " ").trim();
  if (collapsed.length <= limit) return collapsed;
  const cut = collapsed.slice(0, limit);
  const boundary = cut.lastIndexOf(" ");
  return `${(boundary > limit * 0.6 ? cut.slice(0, boundary) : cut).replace(/[,;:.\s]+$/, "")}…`;
}

export function reportReadyEmail({
  locale,
  data,
}: {
  locale: Locale;
  data: ReportReadyData;
}): EmailDocument {
  const message = copy[locale];
  const decisionLabel = message.decision[data.decision];
  const decisionTone = DECISION_TONE[data.decision];
  const confidence = `${Math.round(Math.max(0, Math.min(1, data.confidence)) * 100)}%`;
  const deadline = data.submissionDeadline
    ? formatDate(data.submissionDeadline, locale)
    : null;

  const remaining = data.submissionDeadline
    ? daysUntil(data.submissionDeadline)
    : null;
  const deadlineValue =
    deadline && remaining !== null
      ? remaining < 0
        ? `${deadline} · ${message.deadlinePassed}`
        : `${deadline} · ${message.deadlineDays(remaining)}`
      : message.notProvided;

  const facts: Array<{ label: string; value: string }> = [
    { label: message.buyer, value: data.buyerName ?? message.notProvided },
    { label: message.deadline, value: deadlineValue },
  ];
  if (data.companyName) {
    facts.push({ label: message.preparedFor, value: data.companyName });
  }

  const actions = data.immediateActions.slice(0, 3);

  const content = [
    paragraph(message.intro(data.tenderTitle), { spaceAfter: 24 }),

    // Verdict first: it is the one thing a reader must not have to hunt for.
    calloutPanel(
      [
        `<table width="100%" cellpadding="0" cellspacing="0" role="presentation" style="margin:0 0 10px"><tr>
          <td class="bau-stack" align="left" valign="bottom" style="color:${DECISION_INK[data.decision]};font-size:17px;font-weight:700;letter-spacing:-.02em;line-height:1.3;mso-line-height-rule:exactly">${escapeHtml(decisionLabel)}</td>
          <td class="bau-muted bau-stack" align="right" valign="bottom" style="color:${palette.muted};font-size:12px;white-space:nowrap;line-height:1.3;mso-line-height-rule:exactly">${escapeHtml(message.confidence(confidence))}</td>
        </tr></table>`,
        paragraph(trimHeadline(data.headline), { spaceAfter: 0 }),
      ].join(""),
      decisionTone,
    ),

    statStrip([
      {
        label: message.stats.requirements,
        value: String(data.requirementCount),
      },
      {
        label: message.stats.gaps,
        value: String(data.gapCount),
        tone: data.gapCount > 0 ? "caution" : "positive",
      },
      {
        label: message.stats.risks,
        value: String(data.highRiskCount),
        tone: data.highRiskCount > 0 ? "critical" : "positive",
      },
    ]),

    sectionLabel(message.factsLabel),
    factRows(facts),

    ...(actions.length > 0
      ? [sectionLabel(message.actionsLabel), orderedList(actions)]
      : []),

    button({ href: data.reportUrl, label: message.button }),

    ...(data.requestedByName
      ? [
          paragraph(message.requestedBy(data.requestedByName), {
            tone: "muted",
            spaceAfter: 4,
          }),
        ]
      : []),

    divider(),
    paragraph(message.disclaimer, { tone: "muted", spaceAfter: 0 }),
  ].join("");

  return {
    subject: message.subject(data.tenderTitle),
    html: renderEmail({
      locale,
      preheader: message.preheader(decisionLabel, deadline),
      eyebrow: message.eyebrow,
      title: message.title,
      content,
      footerNote: message.footerNote(data.companyName),
    }),
    text: renderText({
      locale,
      title: message.title,
      lines: [
        message.intro(data.tenderTitle),
        "",
        `${decisionLabel} (${message.confidence(confidence)})`,
        "",
        trimHeadline(data.headline),
        "",
        `${message.stats.requirements}: ${data.requirementCount}`,
        `${message.stats.gaps}: ${data.gapCount}`,
        `${message.stats.risks}: ${data.highRiskCount}`,
        "",
        `${message.buyer}: ${data.buyerName ?? message.notProvided}`,
        `${message.deadline}: ${deadlineValue}`,
        ...(data.companyName
          ? [`${message.preparedFor}: ${data.companyName}`]
          : []),
        ...(actions.length > 0
          ? [
              "",
              `${message.actionsLabel}:`,
              ...actions.map((action, index) => `${index + 1}. ${action}`),
            ]
          : []),
        "",
        `${message.button}: ${data.reportUrl}`,
        ...(data.requestedByName
          ? ["", message.requestedBy(data.requestedByName)]
          : []),
        "",
        message.disclaimer,
      ],
    }),
  };
}
