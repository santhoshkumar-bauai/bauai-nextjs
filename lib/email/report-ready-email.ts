/**
 * "Your tender report is ready."
 *
 * The report takes minutes to write and nobody sits watching the progress bar,
 * so this email is how the analysis actually reaches the team. It therefore has
 * to be readable on its own: a recipient who never opens the link should still
 * come away knowing the verdict, the deadline and whether anything is on fire.
 *
 * What it deliberately does NOT do is reproduce the report. Requirements, risks
 * and evidence belong on the page, where they can be cited and exported; an
 * email that tried to carry them would be unreadable and instantly stale.
 */

export type ReportDecision = "bid" | "conditional" | "no_bid";

export interface ReportReadyData {
  tenderTitle: string;
  buyerName: string | null;
  submissionDeadline: Date | null;
  companyName: string | null;
  decision: ReportDecision;
  /** 0..1, as stored on the report. */
  confidence: number;
  /** Opening paragraph of the executive summary. */
  headline: string;
  requirementCount: number;
  gapCount: number;
  highRiskCount: number;
  /** The `immediate` priority actions, in order. */
  immediateActions: string[];
  reportUrl: string;
  /** Who pressed generate — omitted when it was the recipient themselves. */
  requestedByName: string | null;
}

const DECISION_TONE: Record<ReportDecision, Tone> = {
  bid: "positive",
  conditional: "caution",
  no_bid: "critical",
};

const DECISION_INK: Record<ReportDecision, string> = {
  bid: palette.positiveInk,
  conditional: palette.cautionInk,
  no_bid: palette.criticalInk,
};

